#!/usr/bin/env python3
"""Regenerate the offline file list in service-worker.js.

Run from anywhere after adding, removing or changing app files:
    python3 scripts/build-precache.py

It lists every file the app uses (pages, styles, scripts, pictures, sounds,
icons) and sets a version from their contents, so devices pick up changes.
"""
import hashlib
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {'.git', '.vscode', '.github', 'scripts', 'node_modules'}
SKIP_FILES = {'service-worker.js'}
KEEP_EXT = {'.html', '.css', '.js', '.json', '.png', '.jpg', '.jpeg', '.gif', '.webp', '.svg', '.mp3', '.wav', '.ico'}


def app_files():
    for folder, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith('.'))
        for name in sorted(files):
            if name in SKIP_FILES or os.path.splitext(name)[1].lower() not in KEEP_EXT:
                continue
            yield os.path.relpath(os.path.join(folder, name), ROOT).replace(os.sep, '/')


def main():
    files = list(app_files())
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.encode())
        with open(os.path.join(ROOT, path), 'rb') as handle:
            digest.update(handle.read())
    version = digest.hexdigest()[:12]

    block = (
        '// PRECACHE-START (generated by scripts/build-precache.py; do not edit by hand)\n'
        "const VERSION = '" + version + "';\n"
        'const PRECACHE = ' + json.dumps(['./'] + files, indent=2) + ';\n'
        '// PRECACHE-END'
    )
    sw_path = os.path.join(ROOT, 'service-worker.js')
    with open(sw_path) as handle:
        source = handle.read()
    source = re.sub(r'// PRECACHE-START.*?// PRECACHE-END', lambda _: block, source, flags=re.S)
    with open(sw_path, 'w') as handle:
        handle.write(source)
    print('service-worker.js: %d files, version %s' % (len(files), version))


if __name__ == '__main__':
    main()
